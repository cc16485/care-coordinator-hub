// node tools/build-applicant-words.mjs [path to Staffing-Coordinator-Hub]
// The Applicant journey shows the real interview emails (Samantha, 2026-10-11: "show visuals of the entire application
// and onboarding experience and the texts and emails they receive"). The words live in ONE place, the server's
// supabase/functions/_shared/applicant-words.ts; this copies them into applicant-words.js for the Hub page, types
// removed and nothing else changed. tests/applicant-words-sync-test.mjs fails when the two drift. Re-run after any
// change to the server's wording.
import fs from 'fs'; import path from 'path'; import { stripTypeScriptTypes } from 'module'
const HUB = path.join(path.dirname(new URL(import.meta.url).pathname), '..')
export function build(staffing){
  const src = path.join(staffing, 'supabase/functions/_shared/applicant-words.ts')
  const ts = fs.readFileSync(src, 'utf8')
  const js = stripTypeScriptTypes(ts).replace(/^export /gm, '')
  return '/* GENERATED by tools/build-applicant-words.mjs from Staffing-Coordinator-Hub supabase/functions/_shared/applicant-words.ts.\n'
    + '   Do not edit here: change the server file, then run the tool again. */\n'
    + '(function(){\n' + js + '\nwindow.AP_WORDS = { texts, emails, interviewerLabel, STOP };\n})();\n'
}
if (process.argv[1] && import.meta.url.endsWith(path.basename(process.argv[1]))) {
  const staffing = process.argv[2] || process.env.STAFFING || path.join(HUB, '..', 'Staffing-Coordinator-Hub')
  fs.writeFileSync(path.join(HUB, 'applicant-words.js'), build(staffing))
  console.log('applicant-words.js written from', staffing)
}
